-- Bookings
-- Five bookings are generated for every court. The seven possible time slots
-- are 90 minutes long and never overlap for the same court and date.
WITH booking_seed AS (
    SELECT
        court.id AS court_id,
        slot_number,
        CASE slot_number
            WHEN 1 THEN CURRENT_DATE - (30 + (court.id % 10))::INTEGER
            WHEN 2 THEN CURRENT_DATE - (5 + (court.id % 15))::INTEGER
            WHEN 3 THEN CURRENT_DATE + (1 + (court.id % 7))::INTEGER
            WHEN 4 THEN CURRENT_DATE + (8 + (court.id % 7))::INTEGER
            WHEN 5 THEN CURRENT_DATE + (15 + (court.id % 7))::INTEGER
        END AS booking_date,
        TIME '06:00' + (((court.id + slot_number) % 7) * INTERVAL '2 hours') AS start_time,
        CASE slot_number
            WHEN 1 THEN 'COMPLETED'
            WHEN 2 THEN CASE WHEN court.id % 2 = 0 THEN 'CANCELLED' ELSE 'EXPIRED' END
            WHEN 3 THEN 'CONFIRMED'
            WHEN 4 THEN 'PENDING'
            WHEN 5 THEN 'CONFIRMED'
        END AS status,
        court.price_per_hour
    FROM courts court
    CROSS JOIN GENERATE_SERIES(1, 5) AS generated_booking(slot_number)
),
dated_seed AS (
    SELECT
        booking_seed.*,
        start_time + INTERVAL '90 minutes' AS end_time,
        CASE slot_number
            WHEN 1 THEN booking_date::TIMESTAMP - INTERVAL '2 days'
            WHEN 2 THEN booking_date::TIMESTAMP - INTERVAL '2 days'
            WHEN 3 THEN CURRENT_TIMESTAMP - INTERVAL '2 days'
            WHEN 4 THEN CURRENT_TIMESTAMP - INTERVAL '5 minutes'
            WHEN 5 THEN CURRENT_TIMESTAMP - INTERVAL '1 day'
        END AS created_at
    FROM booking_seed
)
INSERT INTO bookings (
    customer_id, court_id, booking_date, start_time, end_time,
    total_price, required_deposit, status, created_at, updated_at
)
SELECT
    customer.id,
    dated_seed.court_id,
    dated_seed.booking_date,
    dated_seed.start_time,
    dated_seed.end_time,
    ROUND(dated_seed.price_per_hour * 1.50, 2),
    ROUND(dated_seed.price_per_hour * 1.50 * 0.30, 2),
    dated_seed.status,
    dated_seed.created_at,
    CASE dated_seed.slot_number
        WHEN 1 THEN dated_seed.booking_date + dated_seed.end_time + INTERVAL '1 hour'
        WHEN 4 THEN dated_seed.created_at + INTERVAL '1 minute'
        ELSE dated_seed.created_at + INTERVAL '10 minutes'
    END
FROM dated_seed
JOIN users customer
  ON customer.email =
     'customer'
     || ((((dated_seed.court_id - 1) * 5 + dated_seed.slot_number - 1) % 10) + 1)::TEXT
     || '@fieldmate.local';

