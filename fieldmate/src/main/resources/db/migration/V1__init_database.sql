        SELECT 1
        FROM venues venue
        LEFT JOIN courts court ON court.venue_id = venue.id
        GROUP BY venue.id
        HAVING COUNT(court.id) <> 4
    ) THEN
        RAISE EXCEPTION 'Seed validation failed: every venue must have exactly 4 courts';
    END IF;

    SELECT COUNT(*) INTO actual_count FROM courts;
