        SELECT 1
        FROM bookings booking
        JOIN users customer ON customer.id = booking.customer_id
        WHERE customer.role <> 'CUSTOMER'
    ) THEN
        RAISE EXCEPTION 'Seed validation failed: every booking must belong to a CUSTOMER';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM bookings booking
        JOIN users customer ON customer.id = booking.customer_id
        WHERE customer.role = 'ADMIN'
    ) THEN
        RAISE EXCEPTION 'Seed validation failed: an ADMIN owns a booking';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM bookings booking
        JOIN users customer ON customer.id = booking.customer_id
        WHERE customer.role = 'COURT_OWNER'
    ) THEN
        RAISE EXCEPTION 'Seed validation failed: a COURT_OWNER owns a booking';
    END IF;

    IF EXISTS (SELECT 1 FROM bookings WHERE start_time >= end_time) THEN
        RAISE EXCEPTION 'Seed validation failed: booking start_time must be before end_time';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM bookings first_booking
        JOIN bookings second_booking
          ON first_booking.id < second_booking.id
         AND first_booking.court_id = second_booking.court_id
         AND first_booking.booking_date = second_booking.booking_date
         AND first_booking.start_time < second_booking.end_time
         AND first_booking.end_time > second_booking.start_time
        WHERE first_booking.status IN ('CONFIRMED', 'COMPLETED', 'PENDING')
          AND second_booking.status IN ('CONFIRMED', 'COMPLETED', 'PENDING')
          AND NOT (
              first_booking.status = 'PENDING'
              AND first_booking.created_at <= CURRENT_TIMESTAMP - INTERVAL '15 minutes'
          )
          AND NOT (
              second_booking.status = 'PENDING'
              AND second_booking.created_at <= CURRENT_TIMESTAMP - INTERVAL '15 minutes'
          )
    ) THEN
        RAISE EXCEPTION 'Seed validation failed: occupied bookings overlap';
    END IF;

    IF EXISTS (SELECT 1 FROM bookings WHERE total_price <= 0) THEN
        RAISE EXCEPTION 'Seed validation failed: booking total_price must be positive';
    END IF;

    IF EXISTS (
        SELECT 1 FROM bookings
        WHERE required_deposit <= 0 OR required_deposit > total_price
    ) THEN
        RAISE EXCEPTION 'Seed validation failed: invalid required_deposit';
    END IF;
