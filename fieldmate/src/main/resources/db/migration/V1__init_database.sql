BEGIN
    SELECT COUNT(*) INTO actual_count FROM users WHERE role = 'ADMIN';
    IF actual_count <> 1 THEN
        RAISE EXCEPTION 'Seed validation failed: expected 1 ADMIN, found %', actual_count;
    END IF;

    SELECT COUNT(*) INTO actual_count FROM users WHERE role = 'COURT_OWNER';
    IF actual_count <> 4 THEN
        RAISE EXCEPTION 'Seed validation failed: expected 4 COURT_OWNER users, found %', actual_count;
    END IF;

    SELECT COUNT(*) INTO actual_count FROM users WHERE role = 'CUSTOMER';
    IF actual_count <> 10 THEN
        RAISE EXCEPTION 'Seed validation failed: expected 10 CUSTOMER users, found %', actual_count;
    END IF;

    SELECT COUNT(*) INTO actual_count FROM users;
    IF actual_count <> 15 THEN
        RAISE EXCEPTION 'Seed validation failed: expected exactly 15 users, found %', actual_count;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM users owner
        LEFT JOIN venues venue ON venue.owner_id = owner.id
        WHERE owner.role = 'COURT_OWNER'
        GROUP BY owner.id
        HAVING COUNT(venue.id) <> 3
    ) THEN
        RAISE EXCEPTION 'Seed validation failed: every COURT_OWNER must own exactly 3 venues';
    END IF;

    SELECT COUNT(*) INTO actual_count FROM venues;
    IF actual_count <> 12 THEN
        RAISE EXCEPTION 'Seed validation failed: expected exactly 12 venues, found %', actual_count;
    END IF;

